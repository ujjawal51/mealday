import {fileURLToPath} from 'node:url';
import {build} from 'esbuild';
import {createHash} from 'node:crypto';
import {readFile,writeFile,readdir,unlink} from 'node:fs/promises';
const dist=new URL('../dist/',import.meta.url);
const engine=await build({entryPoints:[fileURLToPath(new URL('../dist/recipe-engine-entry.js',import.meta.url))],bundle:true,write:false,format:'iife',target:['es2018'],minify:true,legalComments:'inline'});
const engineData=engine.outputFiles[0].contents;
const engineName='engine-'+createHash('sha256').update(engineData).digest('hex').slice(0,12)+'.js';
await writeFile(new URL(engineName,dist),engineData);
await writeFile(new URL('engine-url.js',dist),'export const engineUrl='+JSON.stringify('/'+engineName)+';\n');
const result=await build({entryPoints:[fileURLToPath(new URL('../dist/app.js',import.meta.url))],bundle:true,write:false,format:'iife',target:['es2018'],minify:true,legalComments:'inline'});
const data=result.outputFiles[0].contents;
const name='client-'+createHash('sha256').update(data).digest('hex').slice(0,12)+'.js';
for(const old of await readdir(dist))if(/^(?:client|engine)-[a-f0-9]+\.js$/.test(old)&&old!==name&&old!==engineName)await unlink(new URL(old,dist));
await writeFile(new URL(name,dist),data);
let html=await readFile(new URL('index.html',dist),'utf8');
html=html.replace(/  <script[^>]+src="\/(?:app|client-[a-f0-9]+)\.js"[^>]*><\/script>/g,'');
html=html.replace(/  <script[^>]+src="\/startup\.js[^\"]*"[^>]*><\/script>/g,'');
html=html.replace(/\n{3,}/g,'\n\n');
html=html.replace('</head>','  <script defer src="/startup.js?v=2"></script>\n  <script defer src="/'+name+'"></script>\n</head>');
await writeFile(new URL('index.html',dist),html);
console.log(name);
